// Run with `bun test scripts/`. Works on temp copies; never touches the real manifests.
import { afterEach, beforeEach, describe, expect, test } from 'bun:test';
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

import { WORKSPACE_PACKAGES } from './set-version';

const repoRoot = resolve(import.meta.dir, '..');
const script = join(repoRoot, 'scripts', 'set-version.ts');

const TOML = `# Workspace root
[workspace]
members = ["crates/pairpane_core", "crates/pairpane_link", "crates/pairpane_remote", "src-tauri"]

[workspace.package]
version = "0.1.0"   # keep me
edition = "2024"

[workspace.dependencies]
serde = { version = "1.0.229" }
`;

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "pairpane_core"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "pairpane_link"
version = "0.1.0"

[[package]]
name = "pairpane_remote"
version = "0.1.0"

[[package]]
name = "pairpane_app"
version = "0.1.0"
dependencies = [
 "pairpane_core",
]

[[package]]
name = "serde"
version = "0.1.0"
`;

let dir: string;
beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'set-version-'));
  writeFileSync(join(dir, 'Cargo.toml'), TOML);
  writeFileSync(join(dir, 'Cargo.lock'), LOCK);
});
afterEach(() => rmSync(dir, { recursive: true, force: true }));

function run(...args: string[]) {
  const result = Bun.spawnSync(['bun', script, ...args, '--root', dir]);
  return { code: result.exitCode, out: result.stdout.toString(), err: result.stderr.toString() };
}
const read = (name: string) => readFileSync(join(dir, name), 'utf8');

describe('set-version', () => {
  test('updates only the workspace version and the workspace crates\' lock entries', () => {
    const { code, out } = run('1.2.3');
    expect(code).toBe(0);
    expect(read('Cargo.toml')).toBe(TOML.replace('version = "0.1.0"   # keep me', 'version = "1.2.3"   # keep me'));
    const lock = read('Cargo.lock');
    expect(lock).toBe(
      LOCK.replace('"pairpane_core"\nversion = "0.1.0"', '"pairpane_core"\nversion = "1.2.3"')
        .replace('"pairpane_link"\nversion = "0.1.0"', '"pairpane_link"\nversion = "1.2.3"')
        .replace('"pairpane_remote"\nversion = "0.1.0"', '"pairpane_remote"\nversion = "1.2.3"')
        .replace('"pairpane_app"\nversion = "0.1.0"', '"pairpane_app"\nversion = "1.2.3"'),
    );
    expect(lock).toContain('name = "serde"\nversion = "0.1.0"');
    expect(out).toContain('Cargo.toml [workspace.package]: 0.1.0 -> 1.2.3');
    expect(out).toContain('Cargo.lock pairpane_core: 0.1.0 -> 1.2.3');
    expect(out).toContain('Cargo.lock pairpane_link: 0.1.0 -> 1.2.3');
    expect(out).toContain('Cargo.lock pairpane_remote: 0.1.0 -> 1.2.3');
    expect(out).toContain('Cargo.lock pairpane_app: 0.1.0 -> 1.2.3');
  });

  test('is idempotent', () => {
    run('2.0.0');
    const toml = read('Cargo.toml');
    const lock = read('Cargo.lock');
    const second = run('2.0.0');
    expect(second.code).toBe(0);
    expect(second.out).toContain('unchanged');
    expect(read('Cargo.toml')).toBe(toml);
    expect(read('Cargo.lock')).toBe(lock);
  });

  test('accepts prerelease and build metadata', () => {
    expect(run('1.0.0-rc.1+build.5').code).toBe(0);
    expect(read('Cargo.toml')).toContain('version = "1.0.0-rc.1+build.5"');
  });

  test.each(['v1.2.3', '1.2', '01.2.3', '1.2.3.4', 'latest', '', '1.2.3-'])('rejects %p and leaves files untouched', (bad) => {
    const result = run(bad);
    expect(result.code).not.toBe(0);
    expect(read('Cargo.toml')).toBe(TOML);
    expect(read('Cargo.lock')).toBe(LOCK);
  });

  test('fails without partial writes when a lock entry is missing', () => {
    const broken = LOCK.replace('name = "pairpane_app"', 'name = "other"');
    writeFileSync(join(dir, 'Cargo.lock'), broken);
    const result = run('3.0.0');
    expect(result.code).toBe(1);
    expect(result.err).toContain('pairpane_app');
    expect(read('Cargo.toml')).toBe(TOML);
    expect(read('Cargo.lock')).toBe(broken);
  });

  test('works on copies of the real manifests and only changes version lines', () => {
    cpSync(join(repoRoot, 'Cargo.toml'), join(dir, 'Cargo.toml'));
    cpSync(join(repoRoot, 'Cargo.lock'), join(dir, 'Cargo.lock'));
    expect(run('9.8.7').code).toBe(0);
    for (const name of ['Cargo.toml', 'Cargo.lock']) {
      const before = readFileSync(join(repoRoot, name), 'utf8').split('\n');
      const after = read(name).split('\n');
      expect(after.length).toBe(before.length);
      const changed = after.filter((line, index) => line !== before[index]);
      expect(changed.every((line) => line === 'version = "9.8.7"')).toBe(true);
      expect(changed.length).toBe(name === 'Cargo.toml' ? 1 : WORKSPACE_PACKAGES.length);
    }
  });

  test('bumps every crate of the real workspace, so the locked release build finds its lock file current', () => {
    const toml = readFileSync(join(repoRoot, 'Cargo.toml'), 'utf8');
    const members = JSON.parse(/^members = (\[.*\])$/m.exec(toml)?.[1] ?? '[]') as string[];
    const names = members.map((member) => {
      const manifest = readFileSync(join(repoRoot, member, 'Cargo.toml'), 'utf8');
      expect(manifest).toContain('version.workspace = true');
      return /^name = "([^"]+)"$/m.exec(manifest)?.[1];
    });

    expect(members.length).toBeGreaterThan(0);
    expect([...names].sort()).toEqual([...WORKSPACE_PACKAGES].sort());
  });

  test("the release workflow's check of the release commit accepts the bump of every workspace crate", () => {
    const workflow = readFileSync(join(repoRoot, '.github', 'workflows', 'release.yml'), 'utf8');
    const pattern = /\^name = "pairpane_\(([a-z|]+)\)"\$/.exec(workflow)?.[1];

    expect(pattern).toBeDefined();
    const allowed = (pattern ?? '').split('|').map((suffix) => `pairpane_${suffix}`);
    expect(allowed.sort()).toEqual([...WORKSPACE_PACKAGES].sort());
  });
});
